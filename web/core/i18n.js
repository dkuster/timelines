// ---------------------------------------------------------------- moteur
const KEY = "tldb-lang";
function stored(){ try { const l = localStorage.getItem(KEY); return LANGS.includes(l) ? l : null; } catch(e){ return null; } }
function detect(){
  const st = stored(); if (st) return st;
  const prefs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || "fr"]);
  for (const p of prefs){ const k = String(p).toLowerCase().slice(0, 2); if (LANGS.includes(k)) return k; }
  return "fr";
}
let cur = detect();
const PR = {};
function plural(n){ const k = cur; if (!PR[k]) PR[k] = new Intl.PluralRules(LOCALES[k] || k); return PR[k].select(Number(n) || 0); }
function t(key, vars){
  let s = STR[cur] && STR[cur][key] !== undefined ? STR[cur][key] : STR.fr[key];
  if (s === undefined) return key;
  if (typeof s === "object") s = s[plural(vars && vars.n)] ?? s.other;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => vars[k] !== undefined ? vars[k] : m) : s;
}
function from(table, key, fallback){ return (table[cur] && table[cur][key]) || table.fr[key] || fallback || key; }
let countryNames = null, countryLang = null;
function country(code){
  if (!code) return "";
  try {
    if (countryLang !== cur){ countryNames = new Intl.DisplayNames([LOCALES[cur] || cur], {type:"region"}); countryLang = cur; }
    return countryNames.of(code) || code;
  } catch(e){ return code; }
}
/** traduit les éléments statiques : data-i18n (texte), data-i18n-html, data-i18n-title, data-i18n-ph (placeholder), data-i18n-aria */
function apply(root){
  root = root || document;
  for (const el of root.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-html]")) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll("[data-i18n-ph]")) el.placeholder = t(el.dataset.i18nPh);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  document.documentElement.lang = cur;
}

export const I18N = {
  LANGS, LOCALES, NAMES, MONTHS, MSHORT, QUAL,
  get lang(){ return cur; },
  /** suit la langue d'affichage du contenu ; « orig » (ou une langue non traduite) garde la langue courante. Renvoie true si elle change. */
  set(l){ if (!LANGS.includes(l) || l === cur) return false; cur = l; return true; },
  /** mémorise un choix explicite de langue, repris par toutes les pages (accueil, frise, mobile) */
  remember(l){ if (LANGS.includes(l)) try { localStorage.setItem(KEY, l); } catch(e){} },
  detect, t, apply, country,
  locale(){ return LOCALES[cur] || cur; },
  type(k){ return from(TYPES, k); },
  fam(id){ return from(FAMS, id); },
  link(type, dir){ const v = (LINKS[cur] && LINKS[cur][type]) || LINKS.fr[type]; return v ? v[dir ? 1 : 0] : type; },
  orgType(k){ return from(ORG_TYPES, k); },
  workType(k){ return from(WORK_TYPES, k); },
  /** pour vérifier qu'aucune clé ne manque : I18N.missing() dans la console */
  missing(){ const out = {}; for (const l of LANGS){ const m = Object.keys(STR.fr).filter(k => !(k in STR[l])); if (m.length) out[l] = m; } return out; }
};

